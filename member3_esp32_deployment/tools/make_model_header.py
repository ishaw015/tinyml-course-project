#!/usr/bin/env python3
"""Reads Member 2's fan_autoencoder_linear.h5 and writes model_weights.h."""
import sys, h5py, numpy as np
h5 = sys.argv[1] if len(sys.argv) > 1 else "tools/fan_autoencoder_linear.h5"
out = sys.argv[2] if len(sys.argv) > 2 else "esp32_firmware/fan_anomaly/model_weights.h"
f = h5py.File(h5, "r")
g = lambda p: np.asarray(f["model_weights/" + p], dtype=np.float32)
W1 = g("dense_2/sequential_1/dense_2/kernel"); B1 = g("dense_2/sequential_1/dense_2/bias")
W2 = g("dense_3/sequential_1/dense_3/kernel"); B2 = g("dense_3/sequential_1/dense_3/bias")
def fmt(a):
    if a.ndim == 1: return "{ " + ", ".join(f"{v:.9e}f" for v in a) + " }"
    return "{ " + ", ".join(fmt(r) for r in a) + " }"
def arr(n, a): return f"static const float {n}" + "".join(f"[{d}]" for d in a.shape) + f" = {fmt(a)};\n"
open(out, "w").write(
"// AUTO-GENERATED by tools/make_model_header.py from fan_autoencoder_linear.h5 -- do not edit.\n"
"// x[3] -> Dense(2, ReLU) -> Dense(3, linear). Dropout is a no-op at inference.\n"
"#ifndef MODEL_WEIGHTS_H\n#define MODEL_WEIGHTS_H\n\n#define MODEL_HIDDEN 2\n"
+ arr("MODEL_W1", W1) + arr("MODEL_B1", B1) + arr("MODEL_W2", W2) + arr("MODEL_B2", B2) + "\n#endif\n")
np.savez("tools/weights.npz", W1=W1, B1=B1, W2=W2, B2=B2)
print("wrote", out)
