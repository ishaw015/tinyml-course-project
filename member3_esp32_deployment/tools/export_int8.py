import numpy as np, tensorflow as tf, sys
from pathlib import Path
T = Path(__file__).resolve().parent
repo = Path(sys.argv[1])
F = T.parent/"esp32_firmware/fan_anomaly"
it = tf.lite.Interpreter(model_path=str(T/"fan_autoencoder_int8.tflite"))
it.allocate_tensors()
D = {t["index"]: t for t in it.get_tensor_details()}
g = lambda k: it.get_tensor(k)

def sc(k):
    return np.asarray(D[k]["quantization_parameters"]["scales"], dtype=np.float64)

s_in = sc(0)[0]; zp_in = int(D[0]["quantization_parameters"]["zero_points"][0])
W1 = g(3).astype(np.int8); sw1 = sc(3)
s_h = sc(4)[0]; zp_h = int(D[4]["quantization_parameters"]["zero_points"][0])
W2 = g(2).astype(np.int8); sw2 = sc(2)
B2 = g(1).astype(np.int32)
s_o = sc(5)[0]; zp_o = int(D[5]["quantization_parameters"]["zero_points"][0])
M1 = (s_in*sw1/s_h).astype(np.float32)
M2 = (s_h*sw2/s_o).astype(np.float32)
assert zp_h == 0
np.savez(T/"int8_params.npz", W1=W1, W2=W2, B2=B2, M1=M1, M2=M2,
         s_in=np.float32(s_in), zp_in=zp_in, s_o=np.float32(s_o), zp_o=zp_o)
print("W1", W1.tolist(), "W2", W2.tolist(), "B2", B2.tolist(), "M1", M1, "M2", M2, "zp", zp_in, zp_o)

def ref(mad):
    xq = np.clip(np.round(mad/np.float32(s_in))+zp_in, -128, 127).astype(np.int64)
    a1 = (xq-zp_in) @ W1.astype(np.int64).T
    hq = np.clip(np.round(a1.astype(np.float32)*M1), 0, 127).astype(np.int64)
    a2 = hq @ W2.astype(np.int64).T + B2.astype(np.int64)
    yq = np.clip(np.round(a2.astype(np.float32)*M2)+zp_o, -128, 127)
    return yq.astype(np.int8), hq

i = it.get_input_details()[0]["index"]
o = it.get_output_details()[0]["index"]
d = np.load(repo/"member1_data_analysis/processed_data/fan_dataset.npz", allow_pickle=True)
X = np.concatenate([d[k] for k in ("X_train", "X_val", "X_test_normal", "X_test_anomaly")]).astype(np.float32)
bad = 0; hid = 0
for x in X:
    q = np.clip(np.round(x/np.float32(s_in))+zp_in, -128, 127).astype(np.int8).reshape(1, 3)
    it.set_tensor(i, q); it.invoke(); y = it.get_tensor(o)[0]
    r, h = ref(x)
    bad += int((y != r).any()); hid += int(h.any())
print("vectors", len(X), "mismatches", bad, "inputs with nonzero hidden", hid)

thr = float((T/"threshold_int8.txt").read_text())
a = lambda n, v, t: f"static const {t} {n} = {{ " + ", ".join(map(str, v)) + " };\n"
f = lambda v: [f"{x:.9e}f" for x in np.ravel(v)]
open(F/"model_int8.h", "w").write(
    "// AUTO-GENERATED by tools/export_int8.py -- do not edit. INT8 PTQ model: x[3] -> Dense(2,ReLU) -> Dense(3)\n"
    "#ifndef MODEL_INT8_H\n#define MODEL_INT8_H\n#include <stdint.h>\n"
    f"#define Q_S_IN {np.float32(s_in):.9e}f\n#define Q_ZP_IN {zp_in}\n#define Q_S_OUT {np.float32(s_o):.9e}f\n#define Q_ZP_OUT {zp_o}\n"
    + a("Q_W1[6]", W1.ravel().tolist(), "int8_t") + a("Q_W2[6]", W2.ravel().tolist(), "int8_t")
    + a("Q_B2[3]", B2.tolist(), "int32_t") + a("Q_M1[2]", f(M1), "float") + a("Q_M2[3]", f(M2), "float") + "#endif\n")
print("thr", thr)